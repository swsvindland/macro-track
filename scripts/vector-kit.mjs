/**
 * Kit files whose bytes differ from the manifest, missing required files (per the repo's profile: Swift only with
 * targets/, eslint.vector.cjs only for ESLint), and unknown files in src/vector.
 */
function driftReport(root, m, config = repoConfig(root)) {
  const problems = [];
  for (const [key, hashes] of Object.entries(m.files)) {
    const variants = key.split("|");
    const expected = hashes.split("|");
    const present = variants.filter((v) => exists(root, v));
    if (!present.length) {
      if (requiredIn(root, key, m, config)) problems.push(`missing   ${variants.join(" or ")}`);
      continue;
    }
    for (const v of present) {
      if (sha(root, v) !== expected[variants.indexOf(v)]) problems.push(`modified  ${v}`);
    }
  }
  const known = new Set(Object.keys(m.files).flatMap((k) => k.split("|")));
  for (const f of walk(abs(root, "src/vector"))) {
    const file = `src/vector/${f}`;
    if (file !== MANIFEST && !known.has(file))
      problems.push(`unknown   ${file} (src/vector is kit-owned)`);
  }
  return problems;
}

function generatedReport(root, config = repoConfig(root)) {
  const problems = [];
  try {
    for (const [file, text] of Object.entries(generated(root))) {
      if (!exists(root, file) || readText(root, file) !== text)
        problems.push(`stale     ${file} (tokens.json changed without gen)`);
    }
  } catch (e) {
    problems.push(`generate  ${e instanceof Error ? e.message : String(e)}`);
  }
  // The oxlint fragment follows the repo's own vector.config.json (and baseline), not the canonical kit.
  if (!CANONICAL && config.linter === "oxlint") {
    const want = oxlintFragment(config, readAllow(root).eslintFiles);
    if (!exists(root, OXLINT_FRAGMENT))
      problems.push(`missing   ${OXLINT_FRAGMENT} (vector-kit sync writes it for the oxlint profile)`);
    else if (readText(root, OXLINT_FRAGMENT) !== want)
      problems.push(
        `stale     ${OXLINT_FRAGMENT} (${CONFIG} or vector.allow.json changed: run \`vector-kit sync\` from vector-design/kit, or check --baseline)`
      );
  }
  return problems;
}

