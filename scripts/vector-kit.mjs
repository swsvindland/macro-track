/** Custom properties a stylesheet declares (`--name:`), without the dashes; comments are skipped. */
const cssProps = (text) =>
  new Set(
    [...text.replace(/\/\*[\s\S]*?\*\//g, "").matchAll(/(?<![\w-])--([\w-]+)\s*:/g)].map(
      (m) => m[1]
    )
  );

/**
 * What an app's replaced global.css defined that nothing defines once the kit's stylesheet is in place (the kit's
 * tokens, and the repo's installed HeroUI and Tailwind themes). A theme colour (`--color-muted-foreground`) there
 * made utilities (`text-muted-foreground`) that now emit nothing, which `check` counts only once the name is in
 * vector.config.json `removedTokens`; other custom properties leave var() and useCSSVariable readers empty.
 */
function droppedTokenReport(repo, oldCss, config) {
  const known = cssProps(readText(ROOT, TOKENS_CSS));
  const styles = [
    ["heroui-native", "lib/module/styles"],
    ["heroui-native-pro", "lib/module/styles"],
    ["tailwindcss", ""],
  ];
  for (const [pkg, dir] of styles) {
    const base = path.join(repo, "node_modules", pkg, ...dir.split("/").filter(Boolean));
    // theme-*.css are opt-in themes (heroui-native's vibrant one); the default stack never imports them.
    for (const f of walk(base))
      if (f.endsWith(".css") && !/(?:^|\/)theme-[^/]*\.css$/.test(f))
        for (const p of cssProps(fs.readFileSync(path.join(base, f), "utf8"))) known.add(p);
  }
  const dropped = [...cssProps(oldCss)]
    .filter((p) => !known.has(p))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  if (!dropped.length) return [];
  const colours = dropped.filter((p) => p.startsWith("color-")).map((p) => p.slice(6));
  const others = dropped.filter((p) => !p.startsWith("color-"));
  const lines = [];
  if (colours.length) {
    // Every app source counts, shims included: a class there renders through the same stylesheet.
    const texts = walk(abs(repo, "src"))
      .map((f) => `src/${f}`)
      .filter(
        (f) => /\.[cm]?[jt]sx?$/.test(f) && !f.startsWith("src/vector/") && f !== GALLERY_ROUTE
      )
      .map((f) => readText(repo, f));
    const uses = (name) => texts.reduce((n, t) => n + count(t, removedTokenPatterns([name])), 0);
    const one = colours.length === 1;
    lines.push(
      `vector-kit sync: the replaced src/global.css defined ${colours.length} theme colour${one ? "" : "s"} the kit does not; ${one ? "its" : "their"} utilities now emit nothing (MIGRATION S3):`
    );
    for (const name of colours)
      lines.push(`  dropped   --color-${name} (${uses(name)} uses in app code)`);
    const unlisted = colours.filter((name) => !config.removedTokens.includes(name));
    if (unlisted.length)
      lines.push(
        `  list ${one ? "it" : "them"} in ${CONFIG} so check counts each use until it moves to a kit token: "removedTokens": ${JSON.stringify([...config.removedTokens, ...unlisted])}`
      );
  }
  if (others.length)
    lines.push(
      `vector-kit sync: the replaced src/global.css also defined ${others.length} custom propert${others.length === 1 ? "y" : "ies"} nothing defines now (var() and useCSSVariable readers get nothing): ${others.map((p) => `--${p}`).join(", ")}`
    );
  return lines;
}

function sync(repos, { force, include }) {
  requireCanonical("sync");
  if (!repos.length) {
    console.error("usage: vector-kit sync <repo…> [--force] [--include <path>]");
    return 1;
  }
  const m = readJson(ROOT, MANIFEST);
  const canonicalDrift = [...driftReport(ROOT, m), ...generatedReport(ROOT)];
  if (canonicalDrift.length) {
    for (const p of canonicalDrift) console.error(`  ${p}`);
    console.error(
      "vector-kit sync: the canonical kit is not current; run `node scripts/vector-kit.mjs gen` first."
    );
    return 1;
  }
  let status = 0;
  for (const arg of repos) {
    const repo = path.resolve(arg);
    if (!fs.existsSync(path.join(repo, "package.json"))) {
      console.error(`vector-kit sync: ${shown(repo)} is not an app repo (no package.json)`);
      status = 1;
      continue;
    }
    let config;
    try {
      config = repoConfig(repo);
    } catch (e) {
      console.error(`vector-kit sync: ${shown(repo)}: ${e instanceof Error ? e.message : String(e)}`);
      status = 1;
      continue;
    }
    if (exists(repo, MANIFEST) && !force) {
      const local = driftReport(repo, readJson(repo, MANIFEST), config);
      const edited = local.filter((p) => !p.startsWith("missing"));
      if (edited.length) {
        for (const p of edited) console.error(`  ${p}`);
        console.error(
          `vector-kit sync: ${shown(repo)} has local edits to kit files; move them into the kit, or pass --force.`
        );
        status = 1;
        continue;
      }
    }
    const variant = testVariant(repo);
    const targets = hasTargets(repo);
    const files = [];
    for (const key of Object.keys(m.files)) {
      if (key === TESTS) files.push(variant);
      else if (key === SWIFT) {
        if (targets) files.push(key);
      } else if (key === ESLINT_FRAGMENT) {
        // The oxlint profile gets the generated oxlint.vector.json instead.
        if (config.linter === "eslint") files.push(key);
      } else if ((m.optional ?? []).includes(key)) {
        if (exists(repo, key) || include.includes(key)) files.push(key);
      } else files.push(key);
    }
    files.push(MANIFEST);
    const generatedFiles =
      config.linter === "oxlint"
        ? { [OXLINT_FRAGMENT]: oxlintFragment(config, readAllow(repo).eslintFiles) }
        : {};
    // Only the files the repo's own manifest lists are kit-owned there. Anything else at a kit path (the app's
    // global.css before the first sync, or an app file where a newer kit starts shipping one) is app-owned:
    // sync lists it and stops, and replaces it only with --force after the owner has looked. A repo that declares
    // its profile in vector.config.json has opted in: its first sync replaces src/global.css without --force.
    const adopting = !exists(repo, MANIFEST);
    const repoManifest = adopting ? {} : readJson(repo, MANIFEST);
    // The manifest lists the generated fragment for every repo (it is byte-identical everywhere), so a generated
    // file is kit-owned only while it still starts with the generator's header: an eslint-node repo may keep an
    // oxlint.vector.json of its own, which sync must neither delete nor overwrite without --force.
    const owned = new Set([
      ...Object.keys(repoManifest.files ?? {}).flatMap((k) => k.split("|")),
      ...(repoManifest.generated ?? []).filter(
        (f) => exists(repo, f) && readText(repo, f).startsWith(GENERATED_HEADER)
      ),
      MANIFEST,
    ]);
    const differs = (file) =>
      exists(repo, file) &&
      !fs.readFileSync(abs(repo, file)).equals(fs.readFileSync(abs(ROOT, file)));
    const differsText = (file, text) => exists(repo, file) && readText(repo, file) !== text;
    const optedIn = (file) => adopting && config.declared && file === "src/global.css";
    const foreign = [
      ...files.filter((file) => !owned.has(file) && differs(file)),
      ...Object.entries(generatedFiles)
        .filter(([file, text]) => !owned.has(file) && differsText(file, text))
        .map(([file]) => file),
    ];
    const blocking = foreign.filter((f) => !optedIn(f));
    if (blocking.length && !force) {
      for (const f of blocking) console.error(`  app file  ${f}`);
      console.error(
        `vector-kit sync: ${shown(repo)} has ${blocking.length} app-owned files at kit paths; review them (MIGRATION S1), then pass --force to replace them.`
      );
      status = 1;
      continue;
    }
    // What the app's stylesheet defined, read before the kit file replaces it (reported below).
    const replacedCss = foreign.includes("src/global.css")
      ? readText(repo, "src/global.css")
      : null;
    let changed = 0;
    for (const file of files) {
      if (!differs(file) && exists(repo, file)) continue;
      fs.mkdirSync(path.dirname(abs(repo, file)), { recursive: true });
      fs.copyFileSync(abs(ROOT, file), abs(repo, file));
      changed++;
    }
    for (const [file, text] of Object.entries(generatedFiles))
      if (writeIfChanged(repo, file, text)) changed++;
    // Deletes only what an earlier sync shipped and the kit no longer does (an app file in src/vector stays: check
    // reports it as unknown), and the lint fragment of the profile the repo left.
    const keep = new Set([...files, ...Object.keys(generatedFiles)]);
    let removed = 0;
    const strays = [];
    for (const f of walk(abs(repo, "src/vector"))) {
      const file = `src/vector/${f}`;
      if (keep.has(file)) continue;
      if (owned.has(file)) {
        fs.rmSync(abs(repo, file));
        removed++;
      } else strays.push(file);
    }
    for (const file of [ESLINT_FRAGMENT, OXLINT_FRAGMENT]) {
      if (!keep.has(file) && owned.has(file) && exists(repo, file)) {
        fs.rmSync(abs(repo, file));
        removed++;
      }
    }
    console.log(
      `synced vector-kit ${m.version} → ${shown(repo)} (${files.length + Object.keys(generatedFiles).length} files, ${changed} changed${removed ? `, ${removed} removed` : ""}${targets ? "" : ", no targets/: Swift skipped"}, ${path.basename(variant)}${config.profile === "eslint-node" ? "" : `, profile ${config.profile}: ${OXLINT_FRAGMENT} generated`})`
    );
    if (foreign.length) {
      console.warn(
        `vector-kit sync: ${force ? "--force" : `${CONFIG} (declared profile)`} replaced ${foreign.length} app-owned files (review with git diff):`
      );
      for (const f of foreign) console.warn(`  replaced  ${f}`);
      if (foreign.includes("src/global.css"))
        console.warn(
          "  src/global.css is now the kit file: MIGRATION S2 (Tabs → Choices) and S3 (removed tokens) belong in this change."
        );
    }
    if (replacedCss !== null)
      for (const line of droppedTokenReport(repo, replacedCss, config)) console.warn(line);
    for (const f of strays)
      console.warn(
        `vector-kit sync: kept ${f} (not a kit file; src/vector is kit-owned, move it out)`
      );
    // The wiring a profile needs in app-owned files (the sub-apps' eslint-node layout is KIT.md §4).
    const todo = [
      ...profileWarnings(repo, config),
      ...oxfmtWarnings(repo, readJson(repo, MANIFEST), config),
    ];
    const rem = metroRem(repo);
    if (rem && rem.rem !== 16) todo.push(`${rem.file}: remove the rem polyfill (${rem.rem}; Uniwind's default is 16)`);
    if (todo.length) {
      console.warn(`vector-kit sync: app-owned wiring for ${shown(repo)} (KIT.md §4):`);
      for (const t of todo) console.warn(`  todo      ${t}`);
    }
  }
  return status;
}

