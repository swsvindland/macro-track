function writeIfChanged(root, file, text) {
  const target = abs(root, file);
  if (fs.existsSync(target) && fs.readFileSync(target, "utf8") === text) return false;
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, text);
  return true;
}

function walk(dir, base = dir) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith(".")) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full, base));
    else out.push(path.relative(base, full).split(path.sep).join("/"));
  }
  return out.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/** A path glob (`**` any depth, `*` and `?` inside one segment) as an anchored RegExp on repo-relative paths. */
function globRegex(glob) {
  const body = glob
    .replace(/^\.\//, "")
    .split("**")
    .map((part) =>
      part
        .split(/([*?])/)
        .map((t) =>
          t === "*" ? "[^/]*" : t === "?" ? "[^/]" : t.replace(/[.+^${}()|[\]\\]/g, "\\$&")
        )
        .join("")
    )
    .join(".*");
  // "src/components/ui/**" also covers the folder itself; "**/x" also matches a top-level x.
  return new RegExp(`^${body.replace(/^\.\*\//, "(?:.*/)?")}$`);
}
const matchesAny = (globs, file) => globs.some((g) => globRegex(g).test(file));

/** JSON with // and /* comments (oxlint and oxfmt configs), read without a parser dependency. */
const readJsonc = (file) => readJsoncText(fs.readFileSync(file, "utf8"));
function readJsoncText(text) {
  let out = "";
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === '"') {
      const start = i;
      for (i++; i < text.length && text[i] !== '"'; i++) if (text[i] === "\\") i++;
      out += text.slice(start, i + 1);
    } else if (c === "/" && text[i + 1] === "/") {
      while (i < text.length && text[i] !== "\n") i++;
      out += "\n";
    } else if (c === "/" && text[i + 1] === "*") {
      i = text.indexOf("*/", i + 2) + 1;
      if (i === 0) break;
    } else out += c;
  }
  return JSON.parse(out.replace(/,(\s*[}\]])/g, "$1"));
}

