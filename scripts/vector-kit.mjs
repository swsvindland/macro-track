/**
 * The repo's profile (KIT.md §3.5): what the app-owned vector.config.json declares, else detected. With no config
 * and an eslint.config.* (or no oxlint config), it is today's sub-app layout, so body, lift, macro and water need
 * no file. `locales` are the app's own languages (default: the 11 kit languages); `shims` are app code the rules
 * treat as migration shims; `removedTokens` are extra dead token names for the `removed-token` rule.
 */
function repoConfig(root) {
  let declared = {};
  const file = path.join(root, CONFIG);
  if (fs.existsSync(file)) {
    try {
      declared = readJsonc(file);
    } catch (e) {
      throw new Error(`${CONFIG}: ${e instanceof Error ? e.message : String(e)}`, { cause: e });
    }
  }
  const oxlint = [".oxlintrc.json", ".oxlintrc.jsonc", "oxlint.config.ts"].some((f) =>
    fs.existsSync(path.join(root, f))
  );
  const detected = oxlint && !eslintConfigFile(root) ? "oxlint-jest" : "eslint-node";
  const profile = typeof declared.profile === "string" ? declared.profile : detected;
  if (!Object.hasOwn(PROFILES, profile))
    throw new Error(
      `${CONFIG}: unknown profile "${profile}" (${Object.keys(PROFILES).join(" | ")})`
    );
  const list = (v, fallback) =>
    Array.isArray(v) && v.length && v.every((x) => typeof x === "string") ? v : fallback;
  return {
    profile,
    ...PROFILES[profile],
    declared: fs.existsSync(file),
    locales: list(declared.locales, KIT_LANGUAGES),
    shims: list(declared.shims, DEFAULT_SHIMS),
    removedTokens: list(declared.removedTokens, []),
  };
}

