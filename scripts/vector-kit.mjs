const WEB_SUPPORTS = "@supports selector(div > div)";

/** Every declaration in compiled CSS with the at-rules and selectors around it (nesting-aware, comment-safe). */
function cssDeclarations(css) {
  const out = [];
  const stack = [];
  let text = "";
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (c === "/" && css[i + 1] === "*") {
      i = css.indexOf("*/", i + 2) + 1;
      if (i === 0) break;
    } else if (c === '"' || c === "'") {
      const start = i;
      for (i++; i < css.length && css[i] !== c; i++) if (css[i] === "\\") i++;
      text += css.slice(start, i + 1);
    } else if (c === "{") {
      stack.push(text.trim());
      text = "";
    } else if (c === "}" || c === ";") {
      const d = /^\s*(--[\w-]+|[a-z-]+)\s*:\s*([\s\S]*?)\s*$/.exec(text);
      if (d && stack.length) out.push({ path: [...stack], prop: d[1], value: d[2] });
      text = "";
      if (c === "}") stack.pop();
    } else text += c;
  }
  return out;
}

/** color-mix() colours in an installed heroui-native styles/theme.css, whitespace-normalized. */
function heroThemeMixes(nodeModules) {
  const file = path.join(nodeModules, "heroui-native/lib/module/styles/theme.css");
  if (!fs.existsSync(file)) return null;
  const mixes = {};
  for (const d of cssDeclarations(fs.readFileSync(file, "utf8")))
    if (d.prop.startsWith("--color-") && d.value.startsWith("color-mix("))
      mixes[d.prop.slice(8)] = d.value.replace(/\s+/g, " ");
  return mixes;
}

