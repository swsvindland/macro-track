// siblings (version + hash matrix across the sibling repos)

function siblings() {
  const columns = [];
  if (CANONICAL) columns.push({ name: "kit", dir: ROOT, optional: false });
  for (const repo of REPOS) {
    const dir = path.join(SIBLINGS, repo.dir);
    // An optional sibling appears once it exists; it is compared once it has synced the kit.
    if (repo.optional && !fs.existsSync(dir)) continue;
    columns.push({ name: repo.name, dir, optional: !!repo.optional });
  }
  const reference = readJson(ROOT, MANIFEST);
  let mismatch = false;
  const rows = [];
  const synced = columns.map((c) => exists(c.dir, MANIFEST));
  const versions = columns.map((c, i) => (synced[i] ? readJson(c.dir, MANIFEST).version : "—"));
  if (columns.some((c, i) => !c.optional && !synced[i])) mismatch = true;
  if (new Set(versions.filter((v, i) => synced[i])).size > 1) mismatch = true;
  rows.push(["version", ...versions]);
  const configs = columns.map((c) => {
    try {
      return repoConfig(c.dir);
    } catch {
      return { ...PROFILES["eslint-node"], profile: "eslint-node", locales: KIT_LANGUAGES, shims: DEFAULT_SHIMS };
    }
  });
  for (const key of Object.keys(reference.files)) {
    for (const variant of key.split("|")) {
      const cells = columns.map((c) => (exists(c.dir, variant) ? sha(c.dir, variant) : null));
      // An optional sibling that has not synced yet holds its own files (global.css): shown, never compared.
      const compared = cells.filter((cell, i) => cell && (synced[i] || !columns[i].optional));
      if (new Set(compared).size > 1) mismatch = true;
      columns.forEach((c, i) => {
        // A test wrapper variant is picked per repo, so only the key as a whole must be present.
        const need =
          key === TESTS
            ? key.split("|").every((v) => !exists(c.dir, v))
            : requiredIn(c.dir, key, reference, configs[i]);
        if (need && !cells[i] && (synced[i] || !c.optional) && c.name !== "kit") mismatch = true;
      });
      rows.push([variant, ...cells.map(short)]);
    }
  }
  const header = ["file", ...columns.map((c) => c.name)];
  const widths = header.map((h, i) => Math.max(h.length, ...rows.map((r) => String(r[i]).length)));
  const line = (r) => r.map((c, i) => String(c).padEnd(widths[i])).join("  ");
  console.log(line(header));
  for (const r of rows) console.log(line(r));
  const pending = columns.filter((c, i) => c.optional && !synced[i]).map((c) => c.name);
  console.log(
    mismatch
      ? "vector-kit siblings: MISMATCH"
      : `vector-kit siblings: one version (${versions.find((v, i) => synced[i])}), one hash per file${pending.length ? ` (not yet synced: ${pending.join(", ")})` : ""}`
  );
  return mismatch ? 1 : 0;
}

