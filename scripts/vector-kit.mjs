// web colour pins: HeroUI-derived color-mix() colours as hex, mixed in OKLab the way a browser mixes them

const srgbToLinear = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const linearToSrgb = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);

/** #rrggbb → [L, a, b] (Björn Ottosson's OKLab, the space CSS color-mix(in oklab) uses). */
function hexToOklab(hex) {
  const n = parseInt(hex.slice(1), 16);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => srgbToLinear(v / 255));
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return [
    0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  ];
}

/** [L, a, b] + alpha → #rrggbb, or #rrggbbaa when translucent (the forms Uniwind's culori returns on web). */
function oklabToHex([L, a, b], alpha = 1) {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const rgb = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  const byte = (v) =>
    Math.round(Math.min(1, Math.max(0, v)) * 255)
      .toString(16)
      .padStart(2, "0");
  return `#${rgb.map((v) => byte(linearToSrgb(v))).join("")}${alpha < 1 ? byte(alpha) : ""}`;
}

/** A colour operand of color-mix(): var(--token[, fallback]), a named colour or a hex, as [hex, alpha]. */
function mixOperand(T, mode, text) {
  const t = text.trim();
  const v = /^var\(--([\w-]+)(?:\s*,\s*(.+))?\)$/.exec(t);
  if (v) {
    if (T.color[v[1]]) return mixOperand(T, mode, resolveColor(T, mode, v[1]));
    if (v[2]) return mixOperand(T, mode, v[2]);
    throw new Error(`tokens.json heroDerived: unknown token --${v[1]}`);
  }
  if (t === "transparent") return ["#000000", 0];
  if (t === "black") return ["#000000", 1];
  if (t === "white") return ["#ffffff", 1];
  if (HEX.test(t)) return [t, 1];
  throw new Error(`tokens.json heroDerived: cannot mix ${t}`);
}

/**
 * CSS Color 5 color-mix(in oklab, A p%, B q%): premultiplied alpha, an omitted percentage is the rest of 100, and
 * percentages that sum below 100 scale the result's alpha (HeroUI's field-border-hover is 88% + 10%).
 */
function colorMix(T, mode, formula) {
  const inner = /^color-mix\(\s*in oklab\s*,(.*)\)$/.exec(formula.trim())?.[1];
  // Split at top-level commas: an operand such as var(--field-border, var(--border)) has its own.
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; inner !== undefined && i < inner.length; i++) {
    if (inner[i] === "(") depth++;
    else if (inner[i] === ")") depth--;
    else if (inner[i] === "," && depth === 0) {
      parts.push(inner.slice(start, i));
      start = i + 1;
    }
  }
  if (inner !== undefined) parts.push(inner.slice(start));
  if (parts.length !== 2)
    throw new Error(`tokens.json heroDerived: not a color-mix(in oklab, A, B): ${formula}`);
  const [a, b] = parts.map((p) => /^\s*(.+?)(?:\s+([\d.]+)%)?\s*$/.exec(p));
  const m = [null, a[1], a[2], b[1], b[2]];
  let p1 = m[2] === undefined ? null : Number(m[2]) / 100;
  let p2 = m[4] === undefined ? null : Number(m[4]) / 100;
  if (p1 === null && p2 === null) p1 = p2 = 0.5;
  else if (p1 === null) p1 = 1 - p2;
  else if (p2 === null) p2 = 1 - p1;
  const sum = p1 + p2;
  const scale = sum < 1 ? sum : 1;
  p1 /= sum;
  p2 /= sum;
  const [hexA, alphaA] = mixOperand(T, mode, m[1]);
  const [hexB, alphaB] = mixOperand(T, mode, m[3]);
  const A = hexToOklab(hexA);
  const B = hexToOklab(hexB);
  const alpha = alphaA * p1 + alphaB * p2;
  if (alpha === 0) return "#00000000";
  const mixed = A.map((c, i) => (c * alphaA * p1 + B[i] * alphaB * p2) / alpha);
  return oklabToHex(mixed, Math.round(alpha * scale * 1000) / 1000);
}

/**
 * The web pins, per mode: every HeroUI color-mix() colour after the kit's overrides. A plain var() override
 * resolves to a hex in the browser already; a color-mix() override (warning-hover) is pinned with its own formula.
 */
function webPins(T) {
  const overrides = {
    ...Object.fromEntries((T.twInline ?? []).map((k) => [k, `var(--${k})`])),
    "field-border-focus": "var(--focus)",
    ...Object.fromEntries(
      Object.entries(T.twDerived ?? {}).filter(([k]) => !k.startsWith("$"))
    ),
  };
  const out = { light: {}, dark: {} };
  for (const [name, hero] of Object.entries(T.heroDerived ?? {})) {
    if (name.startsWith("$")) continue;
    const formula = overrides[name] ?? hero;
    if (!formula.startsWith("color-mix(")) continue;
    for (const mode of ["light", "dark"]) out[mode][name] = colorMix(T, mode, formula);
  }
  return out;
}

function cssBlock(T) {
  const L = [];
  L.push(
    `/* TOKENS:BEGIN — generated from src/vector/tokens.json by scripts/vector-kit.mjs gen (kit ${T.version}). Do not edit. */`
  );
  L.push("@theme {");
  L.push(
    "  /* Families: only the bundled faces (useFonts aliases). Tailwind font-medium/semibold/bold therefore"
  );
  L.push(
    "     select a family, not a weight; weights are explicit numbers in kit components and the COMPONENTS block. */"
  );
  for (const [k, v] of Object.entries(T.fonts.families)) L.push(`  --font-${k}: "${v}";`);
  L.push("");
  for (const [k, [size, lh]] of Object.entries(T.text)) {
    L.push(`  --text-${k}: ${size}px;`);
    L.push(`  --text-${k}--line-height: ${lh}px;`);
  }
  for (const [k, v] of Object.entries(T.tracking)) L.push(`  --tracking-${k}: ${v};`);
  L.push("");
  L.push(
    "  /* One control/panel radius (4) and one mark radius (2). Monotonic; 3xl=4 means HeroUI can never draw a pill. */"
  );
  for (const [k, v] of Object.entries(T.radius)) L.push(`  --${k}: ${v}px;`);
  L.push("");
  for (const [k, v] of Object.entries(T.static)) L.push(`  --${k}: ${v};`);
  L.push("}");
  L.push("");
  // `static`, like HeroUI's own `@theme inline static`: without it Uniwind's runtime registry has no --color-tint,
  // so useThemeColor('tint') / useCSSVariable('--color-tint') would return undefined (utilities work either way).
  L.push("@theme inline static {");
  for (const k of T.twInline) L.push(`  --color-${k}: var(--${k});`);
  L.push("  --color-field-border-focus: var(--focus);");
  for (const [k, tok] of Object.entries(T.color))
    if (tok.tw) L.push(`  --color-${k}: var(--${k});`);
  for (const [k, v] of Object.entries(T.twDerived ?? {}))
    if (!k.startsWith("$")) L.push(`  --color-${k}: ${v};`);
  L.push("}");
  L.push("");
  L.push("@layer theme {");
  L.push("  :root {");
  for (const mode of ["light", "dark"]) {
    L.push(`    @variant ${mode} {`);
    for (const [k, tok] of Object.entries(T.color)) {
      const v = tok[mode];
      const out = typeof v === "string" && v.startsWith("@") ? `var(--${v.slice(1)})` : lower(v);
      L.push(`      --${k}: ${out};`);
    }
    L.push("    }");
  }
  L.push("  }");
  L.push("}");
  const pins = webPins(T);
  if (Object.keys(pins.light).length) {
    L.push("");
    L.push(
      "/* Web only (Uniwind's `web` variant; native drops it). HeroUI reads these through useThemeColor, and on web its"
    );
    L.push(
      "   colour parser rejects the color-mix() string the browser reports (Button press highlight, Toast): the same"
    );
    L.push(
      "   colours as hex, mixed in OKLab from tokens.json as the browser mixes them (tokens.json heroDerived). */"
    );
    L.push("@layer theme {");
    L.push("  :root {");
    L.push("    @variant web {");
    for (const mode of ["light", "dark"]) {
      L.push(`      @variant ${mode} {`);
      for (const [k, v] of Object.entries(pins[mode])) L.push(`        --color-${k}: ${v};`);
      L.push("      }");
    }
    L.push("    }");
    L.push("  }");
    L.push("}");
  }
  L.push("/* TOKENS:END */");
  return L.join("\n");
}

